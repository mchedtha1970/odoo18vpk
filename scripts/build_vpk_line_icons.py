"""สร้าง vpk_sidebar_menu/static/src/scss/line_icons.scss จาก Lucide (ไอคอนลายเส้น)

    npm pack lucide-static && tar xzf lucide-static-*.tgz
    python3 scripts/build_vpk_line_icons.py package

ไอคอนถูกฝังเป็น data URI ใน CSS (ไม่โหลดจากอินเทอร์เน็ต) ใช้งานด้วย
<span class="vpk-li vpk-li-NAME"/> หรือ mask-image: var(--vpk-li-NAME)
เพิ่มไอคอนใหม่: ใส่ชื่อใน ICONS แล้วรันสคริปต์ใหม่ (ดูชื่อได้ที่ https://lucide.dev/icons)
"""
import json
import re
import sys
from pathlib import Path
from urllib.parse import quote

STROKE_WIDTH = "1.75"

ICONS = [
    # main menus (APP_LINE_ICONS in static/src/js/line_icons.js)
    "app-window", "boxes", "calculator", "clipboard-list", "eraser", "factory",
    "file-check", "file-pen-line", "flask-conical", "folder-open", "globe",
    "id-card", "landmark", "layout-dashboard", "layout-grid", "link",
    "message-circle", "receipt", "settings", "shopping-cart", "trending-up",
    "users", "wallet", "warehouse", "wrench",
    # sidebar controls and systray
    "building-2", "chevron-down", "chevron-right", "chevrons-left",
    "chevrons-right", "clock", "code-xml", "lightbulb", "lock", "lock-open",
    "palette", "panel-left", "search", "square-pen", "sticky-note",
]

OUT = (
    Path(__file__).resolve().parents[1]
    / "odoo18-custom-addons/vpk_sidebar_menu/static/src/scss/line_icons.scss"
)


def svg_data_uri(path):
    svg = path.read_text(encoding="utf-8")
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = re.sub(
        r"<svg[^>]*>",
        lambda m: re.sub(r'\s(class|width|height)="[^"]*"', "", m.group(0)),
        svg,
        count=1,
    )
    svg = re.sub(r'stroke-width="[^"]*"', f'stroke-width="{STROKE_WIDTH}"', svg)
    svg = svg.replace('stroke="currentColor"', 'stroke="#000"')
    svg = re.sub(r">\s+<", "><", " ".join(svg.split())).strip()
    return "data:image/svg+xml," + quote(svg.replace('"', "'"), safe=" '=:/;,()")


def main():
    pkg = Path(sys.argv[1] if len(sys.argv) > 1 else "package")
    version = json.loads((pkg / "package.json").read_text())["version"]
    lines = [
        f"// Generated by scripts/build_vpk_line_icons.py from lucide-static {version}",
        "// Lucide icons: ISC License, Copyright (c) Lucide Icons and Contributors",
        "",
        ":root {",
    ]
    for name in ICONS:
        lines.append(f'    --vpk-li-{name}: url("{svg_data_uri(pkg / "icons" / f"{name}.svg")}");')
    lines += [
        "}",
        "",
        ".vpk-li {",
        "    display: inline-block;",
        "    width: 1em;",
        "    height: 1em;",
        "    flex-shrink: 0;",
        "    vertical-align: -0.125em;",
        "    background-color: currentColor;",
        "    -webkit-mask: var(--vpk-li-img) center / contain no-repeat;",
        "    mask: var(--vpk-li-img) center / contain no-repeat;",
        "}",
        "",
    ]
    lines += [f".vpk-li-{name} {{ --vpk-li-img: var(--vpk-li-{name}); }}" for name in ICONS]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(ICONS)} icons, lucide {version})")


if __name__ == "__main__":
    main()
