TAMBON_RE = re.compile(r"(ตำบล|ต\.|แขวง)\s*([ก-๙A-Za-z0-9.\-/]+)")
AMPHOE_RE = re.compile(r"(อำเภอ|อ\.|เขต)\s*([ก-๙A-Za-z0-9.\-]+)")
PROVINCE_RE = re.compile(r"(จังหวัด|จ\.)\s*[ก-๙A-Za-z0-9.\-]+")
