def is_excluded_model(model_name, origin_module):
    """ตรวจว่าโมเดลนี้เป็นโมเดลระบบที่ต้องซ่อน/ห้ามลบหรือไม่"""
    if not model_name:
        return True
    if origin_module in EXCLUDED_SYSTEM_MODULES:
        return True
    if model_name in EXCLUDED_EXACT_MODELS:
        return True
    if model_name.startswith(EXCLUDED_MODEL_PREFIXES):
        return True
    return False


