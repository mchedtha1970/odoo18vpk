def set_run(run, size=12, bold=False, color=SLATE, font_name="Prompt"):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    run.font.name = font_name
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    for attr in ("w:ascii", "w:hAnsi", "w:eastAsia", "w:cs"):
        rFonts.set(qn(attr), font_name)


def add_text(p, text, size=12, bold=False, color=SLATE):
    run = p.add_run(text)
    set_run(run, size, bold, color)
    return run


def shade_cell(cell, hex_color):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    tcPr.append(shd)


def set_cell_border(cell, color="CBD5E1"):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcBorders = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:space"), "0")
        el.set(qn("w:color"), color)
        tcBorders.append(el)
    tcPr.append(tcBorders)


def set_narrow_cell_margin(cell):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcMar = OxmlElement("w:tcMar")
    for m in ("top", "left", "bottom", "right"):
        node = OxmlElement(f"w:{m}")
        node.set(qn("w:w"), "80")
        node.set(qn("w:type"), "dxa")
        tcMar.append(node)
    tcPr.append(tcMar)


def set_cell_width(cell, cm):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcW = tcPr.find(qn("w:tcW"))
    if tcW is None:
        tcW = OxmlElement("w:tcW")
        tcPr.append(tcW)
    twips = str(int(cm * 567))
    tcW.set(qn("w:w"), twips)
    tcW.set(qn("w:type"), "dxa")
    cell.width = Cm(cm)


def cell_text(cell, text, size=9, bold=False, color=SLATE, align="left", fill=None):
    if fill:
        shade_cell(cell, fill)
    set_cell_border(cell)
    set_narrow_cell_margin(cell)
    align_map = {
        "left": WD_ALIGN_PARAGRAPH.LEFT,
        "center": WD_ALIGN_PARAGRAPH.CENTER,
        "right": WD_ALIGN_PARAGRAPH.RIGHT,
    }
    lines = (text or "").split("\n")
    p = cell.paragraphs[0]
    p.alignment = align_map[align]
    p.clear()
    p.paragraph_format.space_before = Pt(1)
    p.paragraph_format.space_after = Pt(1)
    add_text(p, lines[0] if lines else "", size, bold, color)
    for line in lines[1:]:
        np = cell.add_paragraph()
        np.alignment = align_map[align]
        np.paragraph_format.space_before = Pt(0)
        np.paragraph_format.space_after = Pt(1)
        add_text(np, line, size, bold, color)


def set_table_full_width(table, widths):
    tbl = table._tbl
    tblPr = tbl.tblPr
    tblW = tblPr.find(qn("w:tblW"))
    if tblW is None:
        tblW = OxmlElement("w:tblW")
        tblPr.append(tblW)
    total = str(int(sum(widths) * 567))
    tblW.set(qn("w:w"), total)
    tblW.set(qn("w:type"), "dxa")
    grid = tbl.find(qn("w:tblGrid"))
    if grid is not None:
        for i, child in enumerate(list(grid)):
            grid.remove(child)
        for w in widths:
            gridCol = OxmlElement("w:gridCol")
            gridCol.set(qn("w:w"), str(int(w * 567)))
            grid.append(gridCol)
    for row in table.rows:
        for i, w in enumerate(widths):
            set_cell_width(row.cells[i], w)


def prevent_row_split(row):
    tr = row._tr
    trPr = tr.get_or_add_trPr()
    cant = OxmlElement("w:cantSplit")
    trPr.append(cant)


def set_repeat_header(row):
    tr = row._tr
    trPr = tr.get_or_add_trPr()
    tbl_header = OxmlElement("w:tblHeader")
    trPr.append(tbl_header)


def keep_with_next(paragraph):
    pPr = paragraph._p.get_or_add_pPr()
    kn = OxmlElement("w:keepNext")
    pPr.append(kn)


def add_case_table(doc, cases):
    widths = [2.6, 3.0, 2.7, 3.5, 7.2, 5.4, 2.4]
    table = doc.add_table(rows=1 + len(cases), cols=7)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    for i, h in enumerate(HEADERS):
        cell_text(table.rows[0].cells[i], h, 9, True, WHITE, "center", HEADER_FILL)
    for r, case in enumerate(cases, 1):
        fill = ALT_ROW if r % 2 == 0 else "FFFFFF"
        values = [
            case["id"],
            case["step"],
            case["role"],
            case["menu"],
            case["steps"],
            case["expected"],
            RESULT_BOX,
        ]
        aligns = ["center", "left", "left", "left", "left", "left", "center"]
        bolds = [True, True, False, False, False, False, False]
        colors = [DARK_NAVY, SLATE, SLATE, SLATE, SLATE, SLATE, SLATE]
        for c, val in enumerate(values):
            cell_text(
                table.rows[r].cells[c],
                val,
                8.5,
                bolds[c],
                colors[c],
                aligns[c],
                fill,
            )
        prevent_row_split(table.rows[r])
    prevent_row_split(table.rows[0])
    set_repeat_header(table.rows[0])
    set_table_full_width(table, widths)
    return table


