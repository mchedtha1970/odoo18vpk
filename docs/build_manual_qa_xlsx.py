def fill_hex(hex_color):
    return PatternFill("solid", fgColor=hex_color)


def font(size=11, bold=False, color=SLATE, name="Arial"):
    return Font(name=name, size=size, bold=bold, color=color)


def style_header(ws, fill_color):
    for col, title in enumerate(HEADERS, 1):
        cell = ws.cell(1, col, title)
        cell.font = font(11, True, WHITE)
        cell.fill = fill_hex(fill_color)
        cell.alignment = CENTER
        cell.border = THIN
    ws.auto_filter.ref = f"A1:H{ws.max_row}"
    ws.freeze_panes = "A2"
    ws.row_dimensions[1].height = 24
    for col, width in COL_WIDTHS.items():
        ws.column_dimensions[col].width = width
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.page_setup.orientation = "landscape"
    ws.page_setup.fitToPage = True
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.page_setup.paperSize = ws.PAPERSIZE_A4
    ws.page_margins.left = 0.4
    ws.page_margins.right = 0.4
    ws.page_margins.top = 0.5
    ws.page_margins.bottom = 0.5
    ws.oddHeader.left.text = "โรงพยาบาลวชิระภูเก็ต — ข้อสงสัยคู่มือ ERP"
    ws.oddFooter.right.text = "หน้า &P / &N"


def add_status_validation(ws, last_row):
    dv = DataValidation(
        type="list",
        formula1='"รอคำตอบ,ได้คำตอบแล้ว,ต้องปรับคู่มือ,ไม่ต้องปรับ"',
        allow_blank=True,
    )
    dv.error = "เลือกสถานะจากรายการ"
    dv.errorTitle = "สถานะไม่ถูกต้อง"
    dv.prompt = "เลือกสถานะของคำถามนี้"
    dv.promptTitle = "สถานะ"
    ws.add_data_validation(dv)
    dv.add(f"H2:H{last_row}")


def add_status_colors(ws, last_row):
    ws.conditional_formatting.add(
        f"H2:H{last_row}",
        FormulaRule(formula=['H2="รอคำตอบ"'], fill=fill_hex(YELLOW), font=font(11, True, "B45309")),
    )
    ws.conditional_formatting.add(
        f"H2:H{last_row}",
        FormulaRule(formula=['H2="ได้คำตอบแล้ว"'], fill=fill_hex("DBEAFE"), font=font(11, True, BLUE)),
    )
    ws.conditional_formatting.add(
        f"H2:H{last_row}",
        FormulaRule(formula=['H2="ต้องปรับคู่มือ"'], fill=fill_hex("FEE2E2"), font=font(11, True, RED)),
    )
    ws.conditional_formatting.add(
        f"H2:H{last_row}",
        FormulaRule(formula=['H2="ไม่ต้องปรับ"'], fill=fill_hex(LIGHT_GREEN), font=font(11, True, "15803D")),
    )


def write_rows(ws, rows, header_fill):
    extra_blank = 8
    for r, row in enumerate(rows, 2):
        for c, val in enumerate(row, 1):
            cell = ws.cell(r, c, val)
            cell.font = font(10, c in (1, 4, 8))
            cell.alignment = WRAP if c in (5, 6, 7) else Alignment(vertical="top", wrap_text=True)
            cell.border = THIN
            cell.fill = fill_hex(GRAY if r % 2 == 0 else WHITE)
        # Yellow answer cells that are still waiting
        answer = ws.cell(r, 7)
        status = ws.cell(r, 8)
        if (status.value or "") == "รอคำตอบ":
            answer.fill = fill_hex(YELLOW)
            answer.font = font(10, False, "B45309")
            status.fill = fill_hex(YELLOW)
        ws.row_dimensions[r].height = 78

    start_blank = len(rows) + 2
    last = start_blank + extra_blank - 1
    for r in range(start_blank, last + 1):
        for c in range(1, 9):
            cell = ws.cell(r, c, r - 1 if c == 1 else None)
            if c == 1:
                cell.value = r - 1
            cell.font = font(10)
            cell.alignment = WRAP
            cell.border = THIN
            if c == 7:
                cell.fill = fill_hex(YELLOW)
            else:
                cell.fill = fill_hex("FFFBEB")
        ws.cell(r, 8, "รอคำตอบ")
        ws.row_dimensions[r].height = 36

    style_header(ws, header_fill)
    ws.auto_filter.ref = f"A1:H{last}"
    add_status_validation(ws, last)
    add_status_colors(ws, last)
    return last


