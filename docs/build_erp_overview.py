def font(size, bold=False):
    return ImageFont.truetype(FONTB if bold else FONT, size)


_TRAIL = set("ะัิีึืฺุู็่้๊๋์ํๆฯำ")


def _is_trail(word, i):
    ch = word[i]
    if ch in _TRAIL:
        return True
    if ch != "อ":
        return False
    j = i - 1
    while j >= 0 and word[j] in _TRAIL:
        if word[j] in "ืิีึ":
            return True
        j -= 1
    return False


def _cut_word(draw, word, fnt, width):
    cut = 1
    while cut < len(word) and draw.textlength(word[:cut + 1], font=fnt) <= width:
        cut += 1
    while cut < len(word) and _is_trail(word, cut):
        cut += 1
    return max(cut, 1)


def wrap(draw, text, fnt, width):
    lines, cur = [], ""
    for word in text.split(" "):
        trial = word if not cur else cur + " " + word
        if draw.textlength(trial, font=fnt) <= width:
            cur = trial
            continue
        if cur:
            lines.append(cur)
            cur = ""
        while word and draw.textlength(word, font=fnt) > width:
            cut = _cut_word(draw, word, fnt, width)
            lines.append(word[:cut])
            word = word[cut:]
        cur = word
    if cur:
        lines.append(cur)
    return lines


