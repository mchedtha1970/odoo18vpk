        y = title_h + 6 * scale
        draw.rounded_rectangle((x, y, x + col_w, y + head_h), radius=4 * scale, fill=color)
        draw.text((x + pad, y + 2 * scale), name, font=f_head, fill=(255, 255, 255))
        mod_lines = wrap(draw, module, f_mod, col_w - pad * 2)[:2]
        my = y + 14 * scale
        for line in mod_lines:
            draw.text((x + pad, my), line, font=f_mod, fill=(230, 240, 248))
            my += 6 * scale
        y += head_h + 4 * scale
        laid = []
        for code, title, task, doc in items:
            name_lines = wrap(draw, f"{code}  {title}", f_name, body_w)
            task_lines = wrap(draw, task, f_task, body_w)
            doc_lines = wrap(draw, "เอกสาร: " + doc, f_doc, body_w)
            h = pad + len(name_lines) * (7.2 * scale) + len(task_lines) * (6.6 * scale) + len(doc_lines) * (6.2 * scale) + pad
            laid.append((h, name_lines, task_lines, doc_lines))
        gap_c = 3 * scale
        used = sum(h for h, *_ in laid) + gap_c * (len(laid) - 1)
        room = bottom - y
        if used > room and laid:
            shrink = room / used
        else:
            shrink = 1
        for h, name_lines, task_lines, doc_lines in laid:
            h *= shrink
            draw.rounded_rectangle((x, y, x + col_w, y + h), radius=3 * scale, fill=(255, 255, 255), outline=(203, 213, 225))
            draw.rectangle((x, y, x + 2.2 * scale, y + h), fill=color)
            ty = y + pad * shrink
            for line in name_lines:
                draw.text((x + pad + 2, ty), line, font=f_name, fill=color)
                ty += 7.2 * scale * shrink
            for line in task_lines:
                draw.text((x + pad + 2, ty), line, font=f_task, fill=(30, 41, 59))
                ty += 6.6 * scale * shrink
            for line in doc_lines:
                draw.text((x + pad + 2, ty), line, font=f_doc, fill=(100, 116, 139))
                ty += 6.2 * scale * shrink
            y += h + gap_c * shrink
