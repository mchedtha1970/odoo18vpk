def N(title, text):
    return [(title, {"size": 8.5, "bold": True, "color": NAVY}), (text, {"size": 8})]


def gtable(s, y0, cols, rows, sizes, fills=None, x0=0.35, aligns=None, compact=False):
    """ตารางด้วยกล่อง: cols=[(ชื่อ, กว้าง)], rows=[[cell...]] cell เป็น str หรือ list[str]"""
    x = x0
    xs = []
    for name, w in cols:
        xs.append((x, w))
        box(s, x, y0, w - 0.04, 0.32, name, fill=NAVY, line=NAVY, size=10, color=WHITE, bold=True,
            shape=MSO_SHAPE.RECTANGLE)
        x += w
    y = y0 + 0.38
    for r in rows:
        cells = [c if isinstance(c, list) else [c] for c in r]
        h = rows_h(cells, sizes, [w - 0.04 - 0.16 for _, w in cols])
        if compact and h <= 0.6:
            h = 0.35 if all(len(c) == 1 for c in cells) else 0.46
        for ci, ((cx_, cw), cell, sz) in enumerate(zip(xs, cells, sizes)):
            fill = (fills[ci] if fills else WHITE)
            paras = []
            for k, t in enumerate(cell):
                if ci == 0 and k == 0:
                    paras.append((t, {"size": sz, "bold": True, "color": NAVY}))
                elif ci == 1 and k == 0:
                    paras.append((t, {"size": sz, "bold": True, "color": NAVY}))
                else:
                    paras.append((t, {"size": sz if k == 0 else max(sz - 1, 7.5), "color": SLATE if k == 0 else MUTED}))
            al = (aligns[ci] if aligns else (PP_ALIGN.CENTER if ci == 0 else PP_ALIGN.LEFT))
            box(s, cx_, y, cw - 0.04, h, paras, fill=fill, line=LINE, lw=0.75, shape=MSO_SHAPE.RECTANGLE,
                align=al, anchor=MSO_ANCHOR.MIDDLE, margin=0.08)
        y += h + 0.04
    return y


