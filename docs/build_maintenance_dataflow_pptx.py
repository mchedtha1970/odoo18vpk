def slide_overview(prs, page, total):
    s = blank(prs)
    header(s, "ภาพรวมงานซ่อมบำรุง: 8 สาย",
           "ที่มา (Trigger) → ขั้นตอนหลัก → ผลลัพธ์ · สาย C เลือกทาง D / E / F ตามผลประเมิน แล้วไปปิดงานสาย G")
    y0, bh, gap = 0.98, 0.66, 0.04
    for i, (code, name, src, stages, res) in enumerate(OVERVIEW):
        y = y0 + i * (bh + gap)
        col, soft = PHASE_COLOR[code]
        box(s, 0.35, y, 1.9, bh, [(code, {"size": 12, "bold": True, "color": WHITE}),
                                  (name, {"size": 9, "bold": True, "color": WHITE})],
            fill=col, line=col, radius=0.1, margin=0.03)
        box(s, 2.4, y, 2.4, bh,
            [("ที่มา", {"size": 7.5, "bold": True, "color": col})] + [("• " + t, {"size": 8}) for t in src],
            fill=soft, line=col, align=PP_ALIGN.LEFT, radius=0.08, margin=0.05)
        seg(s, 2.25, y + bh / 2, 2.4, y + bh / 2, color=SLATE, w=1.5)
        seg(s, 4.8, y + bh / 2, 4.95, y + bh / 2, color=SLATE, w=1.5)
        n = len(stages)
        cx0, cw_total, ar = 4.95, 5.7, 0.14
        cw = (cw_total - ar * (n - 1)) / n
        for k, st in enumerate(stages):
            x = cx0 + k * (cw + ar)
            box(s, x, y + 0.11, cw, bh - 0.22, st, fill=WHITE, line=col, lw=1.5, size=8, bold=True,
                color=SLATE, radius=0.15, margin=0.03)
            if k < n - 1:
                seg(s, x + cw, y + bh / 2, x + cw + ar, y + bh / 2, color=col, w=1.5)
        seg(s, cx0 + cw_total, y + bh / 2, 10.75, y + bh / 2, color=SLATE, w=1.5)
        box(s, 10.75, y, 2.25, bh,
            [("ผลลัพธ์", {"size": 7.5, "bold": True, "color": GREEN})] + [("• " + t, {"size": 8}) for t in res],
            fill=GREEN_SOFT, line=GREEN, align=PP_ALIGN.LEFT, radius=0.08, margin=0.05)
    yb = y0 + 8 * (bh + gap) + 0.02
    box(s, 0.35, yb, 12.65, 0.4,
        [("สถานะบนคำขอ: ขั้นตอน คำร้องขอใหม่ → กำลังดำเนินการ → ซ่อมแล้ว  ·  สถานะดำเนินการ รอประเมิน → ประเมินแล้ว → "
          "กำลังซ่อม / รออะไหล่ / รอจำหน่าย → ซ่อมเสร็จสิ้น", {"size": 8.5})],
        fill=GREY_SOFT, line=LINE, align=PP_ALIGN.LEFT, radius=0.08, margin=0.12)
    footer(s, page, total)


