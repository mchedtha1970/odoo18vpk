_REV_RE = re.compile(rf"^{re.escape(STEM)}-ver\.(\d+)\.docx$")


def next_manual_rev(out_dir: Path) -> tuple[int, Path]:
    """หาเลข ver สูงสุดที่มีแล้ว แล้วคืน (N+1, path) — ไม่ทับของเดิม"""
    existing = []
    for path in out_dir.glob(f"{STEM}-ver.*.docx"):
        if path.name.startswith("~$"):
            continue
        match = _REV_RE.match(path.name)
        if match:
            existing.append(int(match.group(1)))
    rev = (max(existing) + 1) if existing else 1
    out = out_dir / f"{STEM}-ver.{rev}.docx"
    if out.exists():
        raise FileExistsError(f"ไม่ทับไฟล์ที่มีแล้ว: {out}")
    return rev, out


