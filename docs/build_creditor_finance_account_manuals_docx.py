proc = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(proc)


def header_footer(doc, system_name):
    section = doc.sections[0]
    section.header_distance = Cm(0.8)
    section.footer_distance = Cm(1.0)
    header = section.header
    header.is_linked_to_previous = False
    header.paragraphs[0].text = ""
    footer = section.footer
    footer.is_linked_to_previous = False
    fp = footer.paragraphs[0]
    fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    proc.add_border_line(fp, "top", "C5CDD6", "6")
    proc.add_text(
        fp,
        f"{system_name} · ระบบ ERP รพ.วชิระภูเก็ต | หน้า ",
        9,
        False,
        proc.MUTED,
    )
    run = fp.add_run()
    fld1 = OxmlElement("w:fldChar")
    fld1.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    fld2 = OxmlElement("w:fldChar")
    fld2.set(qn("w:fldCharType"), "end")
    run._r.append(fld1)
    run._r.append(instr)
    run._r.append(fld2)
    proc.set_run(run, 9, False, proc.MUTED)


def open_doc(system_name, title, subtitle, info, chapters):
    doc = Document()
    proc.setup_styles(doc)
    section = doc.sections[0]
    section.page_width = Cm(21.0)
    section.page_height = Cm(29.7)
    section.left_margin = Cm(2.2)
    section.right_margin = Cm(2.2)
    section.top_margin = Cm(2.0)
    section.bottom_margin = Cm(2.2)
    header_footer(doc, system_name)

    logo_p = doc.add_paragraph()
    logo_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    logo_p.paragraph_format.space_before = Pt(12)
    logo_p.paragraph_format.space_after = Pt(8)
    logo_p.add_run().add_picture(str(proc.LOGO), width=Cm(3.4))

    hosp = doc.add_paragraph()
    hosp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    hosp.paragraph_format.space_after = Pt(0)
    proc.add_text(hosp, "โรงพยาบาลวชิระภูเก็ต", 16, True, proc.SLATE)
    hosp_en = doc.add_paragraph()
    hosp_en.alignment = WD_ALIGN_PARAGRAPH.CENTER
    hosp_en.paragraph_format.space_after = Pt(18)
    proc.add_text(hosp_en, "VACHIRAPHUKET HOSPITAL", 11, True, proc.MUTED)

    dtype = doc.add_paragraph()
    dtype.alignment = WD_ALIGN_PARAGRAPH.CENTER
    dtype.paragraph_format.space_after = Pt(6)
    proc.add_text(dtype, "เอกสารคู่มือการใช้งาน (User Manual)", 13, False, proc.MUTED)

    title_p = doc.add_paragraph()
    title_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_p.paragraph_format.space_after = Pt(4)
    proc.add_text(title_p, title, 28, True, proc.TEAL)

    sub = doc.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub.paragraph_format.space_after = Pt(22)
    proc.add_text(sub, subtitle, 12, True, proc.SLATE)

    table = doc.add_table(rows=len(info), cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, (key, value) in enumerate(info):
        proc.cell_text(table.rows[i].cells[0], key, 11, True, proc.TEAL, "left", proc.META_FILL)
        proc.cell_text(table.rows[i].cells[1], value, 11, False, proc.SLATE, "left", "FFFFFF")
        table.rows[i].cells[0].width = Cm(4.8)
        table.rows[i].cells[1].width = Cm(11.4)
        proc.set_narrow_cell_margin(table.rows[i].cells[0])
        proc.set_narrow_cell_margin(table.rows[i].cells[1])

    doc.add_page_break()
    proc.page_title(doc, "ประวัติการแก้ไขเอกสาร (Document Revision History)", center=True)
    proc.make_table(
        doc,
        ["เวอร์ชัน", "วันที่", "รายละเอียดการแก้ไข", "ผู้จัดทำ"],
        [["1.0", "5 ต.ค. 2569", "จัดทำเอกสารคู่มือฉบับแรก", "ทีมพัฒนาระบบ ERP"]],
        [2.4, 3.0, 7.4, 3.4],
    )

    doc.add_page_break()
    proc.page_title(doc, "สารบัญ")
    for item in chapters:
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(8)
        proc.add_text(p, item, 13, False, proc.SLATE)
    return doc


